async function seed() {
  await initializeDatabase();
  console.log('Seeding products into Drizzle SQLite database...');
  await saveAllProducts(products);
  await saveAllCategories(categories);

  // Write mirror files for catalog
  const dataDir = path.resolve(process.cwd(), 'public', 'uploads', 'data');
  if (!fs.existsSync(dataDir)) {
    fs.mkdirSync(dataDir, { recursive: true });
  }
  fs.writeFileSync(path.resolve(dataDir, 'catalog_products.json'), JSON.stringify(products, null, 2), 'utf8');
  fs.writeFileSync(path.resolve(dataDir, 'catalog_products_backup.json'), JSON.stringify(products, null, 2), 'utf8');
  fs.writeFileSync(path.resolve(dataDir, 'catalog_categories.json'), JSON.stringify(categories, null, 2), 'utf8');

  console.log(`Successfully seeded ${products.length} products and ${categories.length} categories!`);
}

